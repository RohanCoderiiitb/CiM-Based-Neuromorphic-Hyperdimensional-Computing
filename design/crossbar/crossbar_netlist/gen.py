"""Hierarchical SPICE generator for the 2T2R ReRAM crossbar.

    half      one device + its access transistor (1T1R). The transistor is on the BITLINE side: row line - device - x - transistor - bitline.
    cell2t2r  one differential cell: two halves on BL+ / BL- sharing the word line (and, through the row line, the drive).
    grp2_<n>  n contiguous cells on one bitline pair, with the bitline wire segment in front of every cell (the segment is r_bl per pitch).
    macro     rows x (block width) cells: the groups stacked along each bitline pair, one row line per row (broken per macro, driver at BOTH ends),
              sense resistors to a ground rail with a pad.
    array     the macros side by side, the shared supply rail through every row (fed from one or both ends), per-macro ground pads.

Two views of the same circuit:

  full_deck     the hierarchy above, every row and every cell present, the active rows selected by the word-line sources. This is THE artefact.
  reduced_deck  the same elements for simulation economy (transients): only the active rows are instantiated, the bitline between them is lumped. Used by the 1C
                transient studies. Its DC solution is exactly the full view's (an inactive row carries no current: a run of them is a series resistance);
                its capacitance follows 1C's pi-lump convention (see reduced_deck).

Every number comes from an ArraySpec (spec.py), whose defaults are names in studies/crossbar/device/constants.py.
"""
from __future__ import annotations

import numpy as np

from .spec import ArraySpec, R_FLOOR, device_resistance
import device.constants as C
from spice.netlist import OPTIONS as DC_OPTIONS, PTM_LIB

TRAN_OPTIONS = ".options reltol=1e-7 abstol=1e-15 vntol=1e-12 gmin=1e-18 itl1=500 itl4=200 method=gear"
LINE_WIDTH = 150


def f(x: float) -> str:
    return f"{float(x):.17g}"


def _wrap(tokens: list[str], head: str = "") -> str:
    """One logical SPICE line, continued with '+' so that no physical line is longer than LINE_WIDTH."""
    out, cur = [], head
    for t in tokens:
        if len(cur) + 1 + len(t) > LINE_WIDTH and cur.strip():
            out.append(cur)
            cur = "+"
        cur = f"{cur} {t}" if cur else t
    out.append(cur)
    return "\n".join(out)


def _rw(x: float) -> float:
    return max(float(x), R_FLOOR)


# ====================================================================================================================== header and leaf cells
def header(spec: ArraySpec, title: str, tran: bool = False) -> list[str]:
    p = spec.p
    L = [f"* {title}", "* generated by design/crossbar/crossbar_netlist (do not edit; regenerate)",
         TRAN_OPTIONS if tran else DC_OPTIONS,
         ("* --- device law  I = I0 exp(-gap/g0) sinh(V/V0) + GMIN V  (Stanford-PKU read equation, constants.py); the LRS / HRS states are the gaps below"
          if spec.device == "sinh" else
          "* --- device: a FIXED resistor at the read bias, R = V_read / I(V_read) of the Stanford-PKU law (constants.py): R_LRS at gap 0.2 nm, R_HRS at gap 1.7 nm"),
         f".param i0={f(p.i0)} g0={f(p.g0)} v0={f(p.v0)} gmin_dev={f(p.gmin)}",
         f".param gap_lrs={f(p.gap_lrs)} gap_hrs={f(p.gap_hrs)} r_lrs={f(device_resistance(p.gap_lrs, p))} r_hrs={f(device_resistance(p.gap_hrs, p))}",
         "* --- access transistor (linear-equivalent R_tx at the read bias, 1A; a switch gated by the word line) and row driver (a behavioural switch, R_DRV when on)",
         f".param r_tx={f(p.r_tx)} r_drv={f(_rw(spec.r_drv))} v_wl={f(p.v_wl)} v_read={f(p.v_read)}",
         f".model swtx sw(vt={f(p.v_wl / 2)} vh=0 ron={f(p.r_tx)} roff={f(C.R_OFF_OHM)})",
         "* --- wires: ohm per cell pitch",
         f".param r_bl={f(_rw(spec.r_bl))} r_wl={f(_rw(spec.r_wl))}"]
    if spec.tx == "bsim":
        L.append(f".include {PTM_LIB}")
    if spec.caps:
        L += ["* --- parasitic capacitance per pitch: ground share and neighbour-coupling share of c_line (1C convention: cc_fraction/2 to each neighbour)",
              f".param c_line={f(spec.c_line)} cg_node={f(spec.c_line * (1.0 - spec.cc_fraction))} cc_node={f(spec.c_line * spec.cc_fraction / 2.0)} c_sense={f(spec.c_sense)}"]
    return L


def leaf_subckts(spec: ArraySpec) -> list[str]:
    p = spec.p
    L = ["", "* ---------------------------------------------------------------- half: one device + one access transistor (a = gap [nm] or R [ohm])",
         ".subckt half rl wl bl params: a=1"]
    if spec.device == "sinh":
        L.append("Bd rl x I = {i0*exp(-a/g0)}*sinh(V(rl,x)/{v0}) + {gmin_dev}*V(rl,x)")
    else:
        L.append("Rd rl x {a}")
    if spec.tx == "switch":
        L.append("St x bl wl 0 swtx")
    elif spec.tx == "linear":
        L.append("Rt x bl {r_tx}")
    else:
        L.append(f"Mt x wl bl 0 ptm45n_lp W={f(p.tx_w_um * 1e-6)} L={f(p.tx_l_nm * 1e-9)}")
    L += [".ends half", "",
          "* ---------------------------------------------------------------- cell2t2r: the differential cell",
          ".subckt cell2t2r rlp rlm wl blp blm params: ap=1 am=1",
          "Xp rlp wl blp half a={ap}", "Xm rlm wl blm half a={am}", ".ends cell2t2r", "",
          "* ---------------------------------------------------------------- row driver: row line to the supply tap when the word line is high, pulled to 0 V when it is low",
          ".subckt rowdrv sup out en"]
    L += (["* behavioural switch: conductance 1/r_drv times a smooth gate g(V(en)) = (1+tanh((V(en)-v_wl/2)/0.01))/2, exactly 1 / 1e-48 at the two word-line levels",
           "Bu sup out I = V(sup,out)/{r_drv}*0.5*(1+tanh((V(en)-{v_wl/2})/0.01))",
           "Bd out 0 I = V(out)/{r_drv}*0.5*(1-tanh((V(en)-{v_wl/2})/0.01))"] if spec.driver == "switch" else ["Rd sup out {r_drv}"])
    L += [".ends rowdrv"]
    return L


# ====================================================================================================================== group
def _group_subckt(spec: ArraySpec, n: int, pair: bool) -> list[str]:
    """n cells on one bitline pair (pair=True) or n halves on a single bitline. Pins: row-line / word-line per cell, the near bitline pin(s) (towards the
    sense node), then one tap pin per cell row (the bitline node at that cell; the last tap is also the far end the next group continues from)."""
    nm = f"grp{2 if pair else 1}_{n}"
    pins, par = [], []
    for r in range(n):
        pins += ([f"rp{r}", f"rm{r}"] if pair else [f"rl{r}"]) + [f"wl{r}"]
    pins += ["nbp", "nbm"] if pair else ["nb"]
    pins += [f"tp{r}" for r in range(n)] + ([f"tm{r}" for r in range(n)] if pair else [])
    for r in range(n):
        par += ([f"ap{r}=1", f"am{r}=1"] if pair else [f"a{r}=1"])
    par.append("ctop=1")
    L = [_wrap(pins + ["params:"] + par, f".subckt {nm}")]
    for r in range(n):
        prevp = ("nbp" if pair else "nb") if r == 0 else f"tp{r - 1}"
        L.append(f"Rp{r} {prevp} tp{r} {{r_bl}}")
        if pair:
            prevm = "nbm" if r == 0 else f"tm{r - 1}"
            L.append(f"Rm{r} {prevm} tm{r} {{r_bl}}")
            L.append(f"Xc{r} rp{r} rm{r} wl{r} tp{r} tm{r} cell2t2r ap={{ap{r}}} am={{am{r}}}")
        else:
            L.append(f"Xc{r} rl{r} wl{r} tp{r} half a={{a{r}}}")
        if spec.caps:
            top = "*ctop" if r == n - 1 else ""
            L.append(f"Cgp{r} tp{r} 0 {{cg_node{top}}}")
            if pair:
                L.append(f"Cgm{r} tm{r} 0 {{cg_node{top}}}")
                L.append(f"Ccc{r} tp{r} tm{r} {{cc_node{top}}}")
    L.append(f".ends {nm}")
    return L


# ====================================================================================================================== row line
def _rowline_subckt(spec: ArraySpec, w: int) -> list[str]:
    nm = f"rowline{w}"
    L = [_wrap([f"w{j}" for j in range(w)], f".subckt {nm} sup wl")]
    L.append("Xd0 sup w0 wl rowdrv")
    if spec.drive_both_ends and w > 1:
        L.append(f"Xd1 sup w{w - 1} wl rowdrv")
    for j in range(1, w):
        L.append(f"Rw{j} w{j - 1} w{j} {{r_wl}}")
    if spec.caps:
        for j in range(w):
            L.append(f"Cw{j} w{j} 0 {{c_line}}")
    L.append(f".ends {nm}")
    return L


# ====================================================================================================================== macro
def _layout(w: int) -> list[tuple[str, int]]:
    """Tile a block of w bitlines into bitline PAIRS (the cells) and, if w is odd, one single bitline (a half-cell column; only the validation uses it)."""
    return [("pair", 2 * c) for c in range(w // 2)] + ([("single", w - 1)] if w % 2 else [])


def _tap(kind_j: tuple[str, int], j: int, r: int) -> str:
    kind, j0 = kind_j
    return f"ts{j}_{r}" if kind == "single" else (f"tp{j0 // 2}_{r}" if j == j0 else f"tm{j0 // 2}_{r}")


def macro_name(b: int, spec: ArraySpec) -> str:
    return f"macro{b}"


def _macro_subckt(spec: ArraySpec, b: int, gaps: np.ndarray | None, rs: np.ndarray, c0: int) -> list[str]:
    """One macro. gaps: (rows, width) state variables (gap or R) of this block, or None for 'all HRS/LRS placeholders'. rs: sense resistors of this block."""
    w, R, g = spec.blocks[b], spec.rows, spec.g
    lay = _layout(w)
    ideal_gnd = spec.r_gnd is None
    pins = [f"wl{r}" for r in range(R)] + [f"rail{r}" for r in range(R)] + [f"s{j}" for j in range(w)] + ["gf", "gl"]
    L = [_wrap(pins, f".subckt {macro_name(b, spec)}")]
    for r in range(R):
        L.append(_wrap([f"w{r}_{j}" for j in range(w)], f"Xr{r} rail{r} wl{r}") + f" rowline{w}")
    state = (lambda r, j: gaps[r, j]) if gaps is not None else (lambda r, j: spec.p.gap_hrs)
    for kind, j0 in lay:
        pair = kind == "pair"
        c = j0 // 2 if pair else j0
        for k in range(spec.n_groups):
            r0, n = k * g, min(g, R - k * g)
            pn = f"grp{2 if pair else 1}_{n}"
            tok = []
            for r in range(r0, r0 + n):
                tok += ([f"w{r}_{j0}", f"w{r}_{j0 + 1}"] if pair else [f"w{r}_{j0}"]) + [f"wl{r}"]
            if k == 0:
                tok += [f"s{j0}", f"s{j0 + 1}"] if pair else [f"s{j0}"]
            else:
                tok += [f"tp{c}_{r0 - 1}", f"tm{c}_{r0 - 1}"] if pair else [f"ts{j0}_{r0 - 1}"]
            tok += [f"tp{c}_{r}" if pair else f"ts{j0}_{r}" for r in range(r0, r0 + n)]
            if pair:
                tok += [f"tm{c}_{r}" for r in range(r0, r0 + n)]
            tok.append(pn)
            for r in range(r0, r0 + n):
                if pair:
                    tok += [f"ap{r - r0}={_sv(spec, state(r, j0))}", f"am{r - r0}={_sv(spec, state(r, j0 + 1))}"]
                else:
                    tok.append(f"a{r - r0}={_sv(spec, state(r, j0))}")
            if spec.caps and k == spec.n_groups - 1:
                tok.append("ctop=0.5")
            L.append(_wrap(tok, f"Xg{c}_{k}" if pair else f"Xs{j0}_{k}"))
    # inter-cell coupling between BL- of one cell and BL+ of the next (the intra-pair coupling is inside the group)
    if spec.caps:
        for jj in range(1, w - 1, 2):
            a, bb = _layout_of(lay, jj), _layout_of(lay, jj + 1)
            for r in range(R):
                span = "*0.5" if r == R - 1 else ""
                L.append(f"Cx{jj}_{r} {_tap(a, jj, r)} {_tap(bb, jj + 1, r)} {{cc_node{span}}}")
    # sense resistors, ground rail (taps: first = pin gf, last = pin gl, the rest local)
    def gtap(j: int) -> str:
        if ideal_gnd or j == 0:
            return "gf"
        return "gl" if j == w - 1 else f"gg{j}"
    for j in range(w):
        L.append(f"Rs{j} s{j} {gtap(j)} {f(rs[j])}")
        if spec.caps:
            L.append(f"Cs{j} s{j} 0 {{c_sense}}")
    if not ideal_gnd:
        rg = _rw(spec.r_gnd)
        for j in range(1, w):
            L.append(f"Rg{j} {gtap(j - 1)} {gtap(j)} {f(rg)}")
        if w == 1:
            L.append("Rgl gf gl 1e-9")        # a one-bitline macro has no separate last tap; nothing uses gl then
    L.append(f".ends {macro_name(b, spec)}")
    return L


def _layout_of(lay, j):
    for kind, j0 in lay:
        if j0 <= j <= (j0 + 1 if kind == "pair" else j0):
            return (kind, j0)
    raise IndexError(j)


def _sv(spec: ArraySpec, gap_or_state: float) -> str:
    """A device state as written in an instance line: the .param name when it is exactly the nominal LRS/HRS state, else the number."""
    p = spec.p
    if spec.device == "sinh":
        if gap_or_state == p.gap_lrs:
            return "{gap_lrs}"
        if gap_or_state == p.gap_hrs:
            return "{gap_hrs}"
        return f(gap_or_state)
    if gap_or_state == float(device_resistance(p.gap_lrs, p)):
        return "{r_lrs}"
    if gap_or_state == float(device_resistance(p.gap_hrs, p)):
        return "{r_hrs}"
    return f(gap_or_state)


# ====================================================================================================================== array and full deck
def full_deck(spec: ArraySpec, gaps: np.ndarray, active, *, title: str = "2T2R ReRAM crossbar", sources: str | None = None, analysis: str = "op",
              tran_stop: float | None = None, tran_step: float = 1e-12, prints: bool = True, extra_prints: list[str] | None = None) -> tuple[str, dict]:
    """The hierarchical netlist of the WHOLE array. gaps: (rows, K) device state in nm (converted to ohm for the 'resistor' device flavour). active: row indices
    whose word line is asserted. Returns (deck text, probes) - probes names the nets a caller prints."""
    R, K, blocks = spec.rows, spec.K, spec.blocks
    gaps = np.asarray(gaps, dtype=float)
    assert gaps.shape == (R, K), (gaps.shape, R, K)
    active = np.zeros(R, bool) if active is None else np.asarray(active)
    if active.dtype != bool:
        m = np.zeros(R, bool); m[active] = True; active = m
    st = spec.gap_to_state(gaps)
    rs = spec.rs
    c0 = spec.col0
    L = header(spec, title, tran=analysis == "tran")
    L += leaf_subckts(spec)
    sizes = sorted({min(spec.g, R - k * spec.g) for k in range(spec.n_groups)})
    L += ["", "* ---------------------------------------------------------------- group: g contiguous cells on one bitline pair (+ a single-bitline variant for odd block widths)"]
    for n in sizes:
        if any(w >= 2 for w in blocks):
            L += _group_subckt(spec, n, True) + [""]
        if any(w % 2 for w in blocks):
            L += _group_subckt(spec, n, False) + [""]
    L += ["* ---------------------------------------------------------------- row line (+ its drivers)"]
    for w in sorted(set(blocks)):
        L += _rowline_subckt(spec, w) + [""]
    L += ["* ---------------------------------------------------------------- macro: rows x block width"]
    for b in range(len(blocks)):
        L += _macro_subckt(spec, b, st[:, c0[b]:c0[b] + blocks[b]], rs[c0[b]:c0[b] + blocks[b]], c0[b]) + [""]
    # array
    L += ["* ---------------------------------------------------------------- array: macros + shared supply rail + ground pads"]
    pins = ["sup"] + [f"wl{r}" for r in range(R)] + [f"s{j}" for j in range(K)]
    L.append(_wrap(pins, ".subckt array"))
    rp = spec.rail_pos_arr
    ideal_sup = spec.r_rail is None
    if not ideal_sup:
        order = np.argsort(rp)
        d = rp[order]
        if d[0] <= 0 or np.any(np.diff(d) <= 0):
            raise ValueError("rail_pos must be positive and distinct")
        rr = _rw(spec.r_rail)
        L.append(f"Rrp sup rail{order[0]} {f(rr * d[0])}")
        for a_, b_ in zip(order[:-1], order[1:]):
            L.append(f"Rr{b_} rail{a_} rail{b_} {f(rr * (rp[b_] - rp[a_]))}")
        if spec.rail_len is not None:
            if spec.rail_len <= d[-1]:
                raise ValueError("rail_length must exceed every rail_pos")
            L.append(f"Rrp2 sup rail{order[-1]} {f(rr * (spec.rail_len - d[-1]))}")
        if spec.caps and spec.c_dec > 0:
            for r in range(R):
                L.append(f"Cdec{r} rail{r} 0 {f(spec.c_dec)}")
    for b in range(len(blocks)):
        tok = [f"wl{r}" for r in range(R)] + [(f"rail{r}" if not ideal_sup else "sup") for r in range(R)] + [f"s{j}" for j in range(c0[b], c0[b] + blocks[b])] + [f"gf{b}", f"gl{b}"]
        L.append(_wrap(tok, f"Xm{b}") + f" {macro_name(b, spec)}")
    if spec.r_gnd is None:
        for b in range(len(blocks)):
            L.append(f"Vgp{b} gf{b} 0 DC 0")
            L.append(f"Vgq{b} gl{b} 0 DC 0")
    else:
        rg = _rw(spec.r_gnd)
        for b in range(len(blocks)):
            if spec.gnd_pad_per_block or b == 0:
                L.append(f"Rgp{b} gf{b} 0 {f(rg * spec.gnd_pad_pitches)}")
            if not spec.gnd_pad_per_block and b > 0:
                L.append(f"Rgb{b} gl{b - 1} gf{b} {f(rg)}")
    L.append(".ends array")
    L += ["", "* ================================================================ testbench"]
    L.append(sources if sources is not None else f"Vsup sup 0 DC {{v_read}}")
    for r in range(R):
        L.append(f"Vwl{r} wl{r} 0 DC {f(spec.p.v_wl) if active[r] else '0'}")
    L.append(_wrap([f"wl{r}" for r in range(R)] + [f"s{j}" for j in range(K)], "Xa sup") + " array")
    probes = dict(sense=[f"s{j}" for j in range(K)],
                  gnd=None if spec.r_gnd is None else [(f"xa.gf{b}" if j == c0[b] else (f"xa.gl{b}" if j == c0[b] + blocks[b] - 1 else f"xa.xm{b}.gg{j - c0[b]}")) for b in range(len(blocks)) for j in range(c0[b], c0[b] + blocks[b])],
                  rail=None if ideal_sup else [f"xa.rail{r}" for r in range(R)],
                  row_nodes=lambda r, cl: f"xa.xm{_block_of(c0, cl)}.w{r}_{cl - c0[_block_of(c0, cl)]}",
                  driver_cols=lambda: [int(c) for b in range(len(blocks)) for c in ([c0[b], c0[b] + blocks[b] - 1] if spec.drive_both_ends and blocks[b] > 1 else [c0[b]])])
    if analysis == "tran":
        cols = ["v(sup)", "i(vsup)"] + [f"v({n})" for n in probes["sense"]]
        L += [f".tran {f(tran_step)} {f(tran_stop)}", ".control", "set noaskquit", "set wr_singlescale", "set wr_vecnames", "set numdgt=12", "run",
              f"wrdata TRANOUT {' '.join(cols)}", ".endc", ".end"]
        return "\n".join(L) + "\n", probes
    L += [".op"]
    if prints:
        pr = [f"print v({n})" for n in probes["sense"]]
        if probes["gnd"] is not None:
            pr += [f"print v({n})" for n in probes["gnd"]]
        for r in np.flatnonzero(active):
            if probes["rail"] is not None:
                pr.append(f"print v({probes['rail'][r]})")
            for cl in probes["driver_cols"]():
                pr.append(f"print v({probes['row_nodes'](r, cl)})")
        pr += [f"print {x}" for x in (extra_prints or [])]
        L += [".control", "set noaskquit", "set numdgt=15", "run"] + pr + [".endc"]
    L.append(".end")
    return "\n".join(L) + "\n", probes


def _block_of(c0, col: int) -> int:
    return int(np.searchsorted(c0, col, side="right") - 1)


def read_full(spec: ArraySpec, probes: dict, v: dict, active) -> dict:
    """Column currents, ground-rail voltages, rail voltages and per-row supply currents from the printed values of a full_deck .op."""
    K, blocks, c0 = spec.K, spec.blocks, spec.col0
    rs = spec.rs
    vs = np.array([v[f"v({n})"] for n in probes["sense"]])
    vg = np.array([v[f"v({n})"] for n in probes["gnd"]]) if probes["gnd"] is not None else np.zeros(K)
    act = np.flatnonzero(np.asarray(active)) if np.asarray(active).dtype == bool else np.asarray(active)
    rail_name = probes["rail"]
    irow, vrail = [], []
    for r in act:
        vr = v[f"v({rail_name[r]})"] if rail_name is not None else spec.p.v_read
        vrail.append(vr)
        irow.append(sum((vr - v[f"v({probes['row_nodes'](r, cl)})"]) for cl in probes["driver_cols"]()) / _rw(spec.r_drv))
    return dict(i_col=(vs - vg) / rs, v_gnd=vg, v_rail=np.array(vrail), i_row=np.array(irow))


# ====================================================================================================================== reduced view (transients)
class TranSpec:
    """Transient settings of reduced_deck (the part of 1C's TranConfig that is not the array itself)."""

    def __init__(self, t_rise: float = C.T_RISE_S, t_stop: float = 2e-9, t_step: float = 1e-12, lump: int = 16, r_pad: float = 0.0, l_pad: float = 0.0,
                 switched_driver: bool = False):
        self.t_rise, self.t_stop, self.t_step, self.lump = t_rise, t_stop, t_step, lump
        self.r_pad, self.l_pad, self.switched_driver = r_pad, l_pad, switched_driver


def reduced_deck(spec: ArraySpec, gaps: np.ndarray, pos: np.ndarray, tr: TranSpec, *, rail_pos=None) -> str:
    """The same circuit as full_deck, for a transient, with only the ACTIVE rows instantiated.

    gaps (n, K): device states of the n active rows; pos (n,): distance of row i from the sense node in cell pitches (row index + 1), strictly increasing.
    Reductions, each exact in DC (the equivalence is checked in validate_netlist.py against the full hierarchy):
      - an inactive row's access transistor is open: it carries no current and no row-line drive, so it is omitted (its bitline segment stays);
      - a run of inactive rows is a series resistance: the bitline is a chain through the active rows with r_bl * (pitch distance).
    Capacitance convention of 1C (pi-lumps): the bitline is distributed along its FULL physical length (rows + the dead-end stub up to row `rows`) in lumps of at
    most tr.lump pitches, each lump carrying half of each adjacent segment; the half of the first segment that faces the sense node is not carried (the sense node has
    its own c_sense). With tr.lump = 1 and every row active this is exactly the per-pitch capacitance of the hierarchical netlist (checked)."""
    n, K = gaps.shape
    blocks = spec.blocks
    assert sum(blocks) == K
    p = spec.p
    c0 = spec.col0
    c0set = set(c0.tolist())
    cdrv = np.concatenate([c0, np.cumsum(blocks) - 1]).astype(int) if spec.drive_both_ends else c0
    rs = spec.rs
    pos = np.asarray(pos, dtype=float)
    bl_len = spec.rows
    xs = np.unique(np.concatenate([pos, np.arange(tr.lump, bl_len + 1, tr.lump, dtype=float), [float(bl_len)]]))
    xs = xs[xs >= 1]
    lo = np.concatenate([[0.0], xs[:-1]]); hi = np.concatenate([xs[1:], [xs[-1]]])
    span = 0.5 * (xs - lo) + 0.5 * (hi - xs)
    span[0] = 0.5 * xs[0] + 0.5 * (xs[1] - xs[0]) if len(xs) > 1 else xs[0]
    cg = spec.c_line * (1.0 - spec.cc_fraction)
    cc = spec.c_line * spec.cc_fraction / 2.0
    src = "vsrc" if (tr.r_pad > 0 or tr.l_pad > 0) else "vpad"
    L = header(spec.with_(caps=False), "reduced transient deck (active rows only)", tran=True)
    L += leaf_subckts(spec)
    L += [f"Vsup {src} 0 DC {f(p.v_read)}" if tr.switched_driver else f"Vsup {src} 0 PWL(0 0 {f(tr.t_rise)} {f(p.v_read)})",
          f"Vwlon wlon 0 DC {f(p.v_wl)}"]
    if src == "vsrc":
        mid = "vp1" if tr.l_pad > 0 else "vpad"
        L.append(f"Rpad vsrc {mid} {f(max(tr.r_pad, 1e-6))}")
        if tr.l_pad > 0:
            L.append(f"Lpad vp1 vpad {f(tr.l_pad)}")
    for j in range(K):
        L.append(f"Rs{j} s{j} 0 {f(rs[j])}")
        L.append(f"Cs{j} s{j} 0 {f(spec.c_sense)}")
        prev, xp = f"s{j}", 0.0
        for k, x in enumerate(xs):
            L.append(f"RB{j}_{k} {prev} b{j}_{k} {f(spec.r_bl * (x - xp))}")
            L.append(f"CB{j}_{k} b{j}_{k} 0 {f(cg * span[k])}")
            if j + 1 < K:
                L.append(f"CC{j}_{k} b{j}_{k} b{j + 1}_{k} {f(cc * span[k])}")
            prev, xp = f"b{j}_{k}", x
    kof = {float(x): k for k, x in enumerate(xs)}
    if spec.r_rail is not None:
        rp = pos if rail_pos is None else np.asarray(rail_pos, dtype=float)
        order = np.argsort(rp)
        rr = max(spec.r_rail, R_FLOOR)
        L.append(f"RRp vpad rail{order[0]} {f(rr * rp[order[0]])}")
        for a_, b_ in zip(order[:-1], order[1:]):
            L.append(f"RR{b_} rail{a_} rail{b_} {f(rr * (rp[b_] - rp[a_]))}")
        if spec.rail_len is not None:
            L.append(f"RRp2 vpad rail{order[-1]} {f(rr * (spec.rail_len - rp[order[-1]]))}")
        if spec.c_dec > 0:
            for i in range(n):
                L.append(f"CD{i} rail{i} 0 {f(spec.c_dec)}")
    st = spec.gap_to_state(np.asarray(gaps, dtype=float))
    for i in range(n):
        k = kof[float(pos[i])]
        for b, c in enumerate(cdrv):
            a_ = "rail" + str(i) if spec.r_rail is not None else "vpad"
            if tr.switched_driver:
                L.append(f"BD{i}_{b} {a_} w{i}_{c} I = V({a_},w{i}_{c})/{f(_rw(spec.r_drv))}*min(1,time/{f(tr.t_rise)})")
            else:
                L.append(f"RD{i}_{b} {a_} w{i}_{c} {f(_rw(spec.r_drv))}")
        for j in range(K):
            if j > 0 and j not in c0set:
                L.append(f"RW{i}_{j} w{i}_{j - 1} w{i}_{j} {f(spec.r_wl)}")
            L.append(f"CW{i}_{j} w{i}_{j} 0 {f(spec.c_line)}")
            L.append(f"X{i}_{j} w{i}_{j} wlon b{j}_{k} half a={f(st[i, j])}")
    cols = [f"v({src})", "i(Vsup)"] + [f"v(s{j})" for j in range(K)] + ([f"v(rail{i})" for i in range(n)] if spec.r_rail is not None else [])
    L += [f".tran {f(tr.t_step)} {f(tr.t_stop)}", ".control", "set noaskquit", "set wr_singlescale", "set wr_vecnames", "set numdgt=12", "run",
          f"wrdata TRANOUT {' '.join(cols)}", ".endc", ".end"]
    return "\n".join(L) + "\n"
