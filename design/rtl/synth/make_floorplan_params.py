#!/usr/bin/env python3
"""innovus/floorplan_params.tcl: die size and macro positions for the owner's Innovus run, computed from the macro LEFs (analog_macros.py) and the pre-route standard-cell area.
Layout: the crossbar macro on top, the digital block UNDER it, against the macro's pin edge (bottom): the 2,178 pin bits
meet the logic that uses them), the small class-array macro in the digital region. UTIL is the target density of the digital region only (the macros are excluded)."""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
ap = argparse.ArgumentParser()
ap.add_argument("--build", default="full")
ap.add_argument("--util", type=float, default=0.65)
ap.add_argument("--margin", type=float, default=30.0)
a = ap.parse_args()
mac = json.loads((HERE / "results" / "analog_macros.json").read_text())
cim = mac["cim_macro"]
hdc = mac["hdc_class_array_fact" if a.build in ("full", "ee_off") else "hdc_class_array_unfact"]
dig = json.loads((ROOT / "results" / "ppa_digital" / a.build / "summary.json").read_text())["buf_fast"]["area_um2"]
m = a.margin
import math
ROW = 1.71
core_y0 = math.ceil(m / ROW) * ROW                      # the core is snapped up to the site-row grid
dig_region = dig / a.util + hdc["area_um2"] * 1.2        # standard cells at the target density + the small class-array macro with halo
W = cim["width_um"] + 2 * m                              # the core is exactly as wide as the crossbar macro
dig_h = dig_region / cim["width_um"]                     # the digital region lies UNDER the macro, against the edge that carries its 2,178 pins (pins at y = 0 of the macro)
cim_y = math.ceil((core_y0 + dig_h) / ROW) * ROW         # macro on a row boundary
H = cim_y + cim["height_um"] + m + 0.1
tcl = f"""# generated by make_floorplan_params.py --build {a.build} --util {a.util}  (do not edit; re-run)
set DIE_W {W:.2f}
set DIE_H {H:.2f}
set MARGIN {m:.1f}
set CIM_X {m:.2f}
set CIM_Y {cim_y:.2f}
set HDC_X {W - m - hdc['width_um'] - 5:.2f}
set HDC_Y {core_y0 + 5:.2f}
set UTIL_TARGET {a.util}
"""
(HERE / "innovus" / "floorplan_params.tcl").write_text(tcl)
print(f"die {W:.0f} x {H:.0f} um = {W * H * 1e-6:.3f} mm^2; crossbar macro {cim['width_um']:.0f} x {cim['height_um']:.0f} on top; digital region {cim['width_um']:.0f} x {dig_h:.0f} under it for {dig:,.0f} um^2 of cells at util {a.util}")
