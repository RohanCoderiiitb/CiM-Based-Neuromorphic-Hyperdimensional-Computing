#!/usr/bin/env python3
"""The LARGE chip (NeuroHDC-large counterpart, ASL-DVS): the repository RTL with package overrides only. No module is edited; every size follows from the packages.
  40 neurons (320 crossbar columns, 10 weight macros, 40 thresholds), 24 classes, 12-bit event counters (ASL-DVS has cell counts up to 3,913), and a 240 x 180 second geometry
  (17-bit AER word p<<16 | y<<8 | x; 128 x 128 stays on the first geometry, unchanged).
Writes design/rtl_large/rtl/ (a generated tree: regenerate, never edit). Simulate with CIM_RTL_ROOT=design/rtl_large, synthesise with run_flow.py --rtl-root design/rtl_large.
   python scripts/make_large_rtl.py [--w-x 21 --w-v 26 --w-thresh 15]"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT.parent / "rtl_large"


def override(text: str, name: str, value: int) -> str:
    pat = rf"(localparam int {name}\s*=\s*)([^;]+)(;)"
    assert len(re.findall(pat, text)) == 1, name
    return re.sub(pat, rf"\g<1>{value}\g<3>  /* LARGE override */", text)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--w-x", type=int, default=21)
    ap.add_argument("--w-v", type=int, default=26)
    ap.add_argument("--w-thresh", type=int, default=15)
    a = ap.parse_args()
    if OUT.exists():
        shutil.rmtree(OUT / "rtl")
    shutil.copytree(ROOT / "rtl", OUT / "rtl")
    p = OUT / "rtl" / "pkg" / "cim_neurohdc_pkg.sv"
    t = p.read_text()
    for k, v in dict(N_NEURONS=40, W_COUNT=12, AER_SHIFT_NMNIST=8, GEO2_W=240, GEO2_H=180, W_AER=17, COORD_MUL_NMNIST=68, W_X=a.w_x, W_V=a.w_v, W_THRESH=a.w_thresh, N_PARALLEL_COLS_DEFAULT=80, LOCAL_QUERY_BUSY=1, EXIT_CLK_FREE=1).items():
        t = override(t, k, v)
    p.write_text(t)
    h = OUT / "rtl" / "pkg" / "hdc_pkg.sv"
    ht = h.read_text()
    for k, v in dict(N_CLASSES_DEFAULT=24, N_SPK=40, CFG_THETA=64, AGREE_PIPE=1, TOP2_QUARTERS=1).items():
        ht = override(ht, k, v)
    h.write_text(ht)
    (OUT / "README.md").write_text("Generated by design/rtl/scripts/make_large_rtl.py: the repository RTL with package overrides for the large chip. Do not edit; regenerate.\n")
    print("wrote", OUT / "rtl")


if __name__ == "__main__":
    main()
