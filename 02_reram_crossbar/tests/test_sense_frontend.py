def test_port_model_reproduces_1c_far_group_step():
    from sense import port as P
    far = P.worst_step(P.FAR_POS0)
    assert 33.5e-6 < far < 35.0e-6                   # 1C mesh: 34.1 uA before row-line / rail losses; the port model 34.3 uA
    ip, im = P.levels(P.FAR_POS0)
    assert np.all(np.diff(ip - im) < 0) or np.all(np.diff(ip - im) > 0)     # monotone levels


@ngspice
def test_conveyor_channel_copies_the_array_current():
    from sense import mc, port as P
    from sense.cal import DESIGN
    dz = mc.Design(**DESIGN)
    ip, im = P.levels(P.FAR_POS0)
    a, b = mc.i_channels(dz, 1, P.FAR_POS0)
    assert a == pytest.approx(ip[1], rel=0.05) and b == pytest.approx(im[1], rel=0.06)      # nominal copy within 6% of the ideal-virtual-ground levels (the gain is calibrated per column)


@ngspice
def test_copy_device_mismatch_moves_the_channel_current():
    from sense import cal, mc, port as P
    dz = mc.Design(**cal.DESIGN)
    nom = np.array([mc.i_channels(dz, m, P.FAR_POS0) for m in range(9)])
    assert nom.shape == (9, 2)
    dv = {n: 0.01 for n in dz.devices() if n.startswith("M2")}          # 10 mV on the copy devices
    mis = np.array([mc.i_channels(dz, m, P.FAR_POS0, dv) for m in range(9)])
    assert abs(mis - nom).max() > 1e-6                                   # a real effect (uA scale), not numerical noise
    assert abs(mis / nom - 1).max() < 0.5                                # and a gain error, not a different circuit


@have(RP.SENSE / "calibration_mc.json")
def test_calibration_needs_two_parameters_and_drifts_with_temperature():
    c = json.loads((RP.SENSE / "calibration_mc.json").read_text())
    assert c["raw"]["rms_uA"] > 20                                       # uncalibrated mismatch is far above the 12 uA budget limit
    g, go = c["gain_only"]["27"], c["gain_and_offset"]["27"]
    assert go["sigma_worst_point_uA"] < 0.5 < g["sigma_worst_point_uA"]  # one parameter is not enough, two are
    r = [c["gain_and_offset"][f"{t:g}"]["rms_uA"] for t in c["temps"]]
    assert r == sorted(r)                                                # the residual grows with the temperature offset from calibration


@have(RP.SENSE / "topology_comparison.json")
def test_only_the_conveyor_holds_the_virtual_ground_at_equal_power():
    t = json.loads((RP.SENSE / "topology_comparison.json").read_text())
    row = lambda nm, s: [r for r in t["rows"] if r["topology"] == nm and r["ota_scale"] == s and r["group"] == "far" and abs(r["T"] - 1e-9) < 1e-15][0]
    assert row("b", 1)["step_ratio_min"] > 0.7
    for nm, s in (("a", 1), ("d", 1), ("d2", 1)):
        assert row(nm, s)["step_ratio_min"] < 0.65
    assert t["supply"]["c x1"][1] > 0.5                                  # (c) forces the node to ~0.54 V: the row supply would have to be 0.64 V


