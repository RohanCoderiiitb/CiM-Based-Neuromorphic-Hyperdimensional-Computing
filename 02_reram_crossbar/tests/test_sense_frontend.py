@have(RP.SENSE / "energy_per_inference_1f.json")
def test_energy_components_sum_and_sense_dominates():
    from sense import energy_1f as E
    e = E.energy(0.46, 1e-9, 0.3e-9, 8)
    assert e["total_J"] == pytest.approx(e["array_J"] + e["wordline_J"] + e["sense_bias_J"] + e["decision_J"] + e["threshold_J"], rel=1e-12)
    assert e["sense_bias_J"] > e["array_J"]                              # the front-end, not the array, sets the energy
    assert E.energy(0.46, 2e-9, 0.3e-9, 8)["total_J"] > e["total_J"]     # linear in the pulse length


@have(RP.PDN / "pdn_sweep.json")
def test_pdn_droop_falls_with_decoupling_and_charge_scales_with_current():
    p = json.loads((RP.PDN / "pdn_sweep.json").read_text())
    sel = sorted([x for x in p if x["t_pulse"] == 1e-9 and x["r_d"] == 0.1 and x["stagger"] == 0.0 and x.get("i_scale", 1.0) == 1.0 and x["c_dec"] > 0], key=lambda x: x["c_dec"])
    d = [x["droop_max_mV"] for x in sel]
    assert d == sorted(d, reverse=True)
    q = 0.0692 * 1e-9                                                    # 69.2 mA x 1 ns: the droop at the largest C is bounded below by Q / C
    assert sel[-1]["droop_max_mV"] * 1e-3 >= 0.5 * q / sel[-1]["c_dec"]


